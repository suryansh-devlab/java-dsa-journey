package code.Basic;

public class Variables {
    public static void main(String[] args) {

        // Variables:-
        int x; // Declaration
        x = 20; // Initialization
        System.out.println(x);

        int a = 10; // Declaration and Initialization
        System.out.println(a);
        System.out.println(x * a);

        // Arithmetic Operations

        int y = 50;

        System.out.println(y);
        y = y + 20;
        System.out.println(y);
        y = y - 30;
        System.out.println(y);
        y = y * 5;
        System.out.println(y);
        y = y / 10;
        System.out.println(y);

    }
}
